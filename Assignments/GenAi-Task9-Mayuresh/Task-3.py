import numpy as np

values = np.array([2,4,6,8,10])

square_root = np.sqrt(values)
exponential = np.exp(values)
natural_log = np.log(values)
sum_values = np.sum(values)
cumulative_sum = np.cumsum(values)

print(square_root)
print(exponential)
print(natural_log)
print(sum_values) 
print(cumulative_sum)